import assert from 'node:assert/strict';
import {fixture, Emitter} from './runtime-harness.mjs';
const {ext, Main} = fixture();
assert.doesNotThrow(() => ext.setPanelBoxPosition('Top'), 'startup without monitors');
assert.doesNotThrow(() => ext.connectPrimaryBGChanged(), 'background manager absent');
const old = new Emitter(), current = new Emitter();
Main.layoutManager.monitors = [{x:0,y:0,width:1024,height:768}];
Main.layoutManager.primaryIndex = 0; Main.layoutManager._bgManagers = [old];
ext.connectPrimaryBGChanged(); ext.connectPrimaryBGChanged();
assert.equal(old.count('changed'), 1, 'idempotent manager binding');
assert.equal(ext._bgSettings.count('changed::picture-uri'), 1, 'one permanent wallpaper subscription');
Main.layoutManager.monitors = []; Main.layoutManager.primaryIndex = -1;
ext.connectPrimaryBGChanged();
assert.equal(old.count('changed'), 0, 'lost monitor releases old manager');
Main.layoutManager.monitors = [{x:0,y:0,width:1920,height:1080}];
Main.layoutManager.primaryIndex = 0; Main.layoutManager._bgManagers = [current];
ext.connectPrimaryBGChanged();
assert.equal(current.count('changed'), 1);
assert.equal(ext._intSettings.count('changed::color-scheme'), 1);
assert.equal(ext._settings.values['monitor-width'], 1920);
assert.equal(ext._settings.values['monitor-height'], 1080);
Main.layoutManager.monitors = [];
assert.doesNotThrow(() => ext.setPanelBoxPosition('Top'), 'disable position reset while absent');
ext._connections.disconnectAll();
assert.equal(current.count('changed'), 0);
console.log('runtime monitor regression: PASS');
